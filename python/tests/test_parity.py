def test_scan_windows(expected, x60, F4):
    from scipy.stats import norm
    sc = fc.wilcoxon_scan(x60, 0.25)
    assert sc["stat"] == pytest.approx(expected["scan_wilcoxon|stat"], rel=RTOL)
    assert sc["k"] == int(expected["scan_wilcoxon|k"])
    assert sc["m"] == int(expected["scan_wilcoxon|m"])
    sc = fc.lp_scan(x60, 0.25, cdf=norm.cdf)
    assert sc["stat"] == pytest.approx(expected["scan_lp|stat"], rel=RTOL)
    assert sc["k"] == int(expected["scan_lp|k"])
    assert sc["m"] == int(expected["scan_lp|m"])
    sc = fc.rkhs_scan(x60, 0.25, kernel="gaussian")
    assert sc["stat"] == pytest.approx(expected["scan_rkhs|stat"], rel=RTOL)
    assert sc["k"] == int(expected["scan_rkhs|k"])
    assert sc["m"] == int(expected["scan_rkhs|m"])
    sc = fc.far1_scan(F4, 0.4)
    assert sc["stat"] == pytest.approx(expected["scan_far1|stat"], rel=RTOL)
    assert sc["k"] == int(expected["scan_far1|k"])
    assert sc["m"] == int(expected["scan_far1|m"])


def test_critical_values_bit_parity(expected):
    """Same frozen draws + same quantile definition -> 1e-12 agreement."""
    for g in (0, 0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.35, 0.4, 0.45, 0.495):
        assert fc.wilcoxon_critical_value(g) == pytest.approx(
            expected[f"cv_wilcoxon|g={g:g}|b=0"], rel=1e-12)
    assert fc.wilcoxon_critical_value(0.5, beta=1) == pytest.approx(
        expected["cv_wilcoxon|g=0.5|b=1"], rel=1e-12)
    assert fc.wilcoxon_critical_value(0.25, splits=2) == pytest.approx(
        expected["cv_wilcoxon_s2|g=0.25"], rel=1e-12)
    for g in GAMMAS:
        for p in (2, 4, 10):
            assert fc.lp_critical_value(g, p) == pytest.approx(
                expected[f"cv_lp|g={g:g}|p={p}"], rel=1e-12)
    cells = (("gaussian", ""), ("min", "rnorm.sq"), ("min", "runif"),
             ("2max", "runif"), ("2max", "rbeta.1.9"))
    for g in GAMMAS:
        for kernel, baseline in cells:
            assert fc.rkhs_critical_value(g, kernel, baseline) == \
                pytest.approx(expected[f"cv_rkhs|g={g:g}|k={kernel}|b={baseline}"],
                              rel=1e-12)
    for g in (0, 0.25, 0.4, 0.45):
        assert fc.far1_critical_value(g) == pytest.approx(
            expected[f"cv_far1|g={g:g}"], rel=1e-12)


def test_kuiper(expected):
    assert fc.kuiper_quantile(0.95) == pytest.approx(
        expected["kuiper_q|p=0.95"], rel=1e-9)
    assert fc.kuiper_cdf(1.7473) == pytest.approx(
        expected["kuiper_cdf|v=1.7473"], rel=1e-12)


def test_projection_l2_and_reconstruction(F5):
    np.testing.assert_allclose(fc.project_l2(F5), load_vec("expected_l2.csv"),
                               rtol=1e-12)
    r = fc.reconstruct(F5, "fs_interp", K=4)
    np.testing.assert_allclose(r["X"], load_mat("expected_fsinterp.csv"),
                               rtol=1e-10)
    r = fc.reconstruct(F5, "fs_ls", K=4)
    np.testing.assert_allclose(r["X"], load_mat("expected_fsls.csv"),
                               rtol=1e-8)
