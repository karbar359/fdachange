"""Cross-language parity: Python results vs the R reference implementation
on identical inputs (fixtures generated by tools/make_fixtures.R)."""

from __future__ import annotations

import numpy as np
import pytest

import fdachange as fc

from conftest import load_mat, load_vec

GAMMAS = (0.0, 0.25, 0.45)
RTOL = 1e-10


def test_wilcoxon_statistics(expected, x60):
    for g in GAMMAS:
        assert fc.wilcoxon_statistic(x60, g) == pytest.approx(
            expected[f"wilcoxon|g={g:g}"], rel=RTOL)
    assert fc.wilcoxon_statistic(x60, 0.25, kernel="h_0") == pytest.approx(
        expected["wilcoxon_h0|g=0.25"], rel=RTOL)
    # vectorised gamma equals the per-gamma calls
    v = fc.wilcoxon_statistic(x60, np.array(GAMMAS))
    for g, val in zip(GAMMAS, v):
        assert val == pytest.approx(expected[f"wilcoxon|g={g:g}"], rel=RTOL)


def test_lp_statistics(expected, x60):
    from scipy.stats import norm
    for g in GAMMAS:
        assert fc.lp_statistic(x60, g, p=2, cdf=norm.cdf) == pytest.approx(
            expected[f"lp_pnorm|g={g:g}"], rel=RTOL)
        assert fc.lp_statistic(x60, g, p=2) == pytest.approx(
            expected[f"lp_ecdf|g={g:g}"], rel=RTOL)
    assert fc.lp_statistic(x60, 0.25, p=4, cdf=norm.cdf) == pytest.approx(
        expected["lp_p4|g=0.25"], rel=RTOL)


