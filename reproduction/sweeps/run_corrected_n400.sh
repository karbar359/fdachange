#!/usr/bin/env bash
# Re-run the entire simulation chapter with the CORRECTED statistics
# (2026-09 audit): Wilcoxon multiply-weight + true window length + Kuiper
# gamma=0 null, Lp with the F_n centring, RKHS printed formula against its
# regenerated null cache, Birbilas printed denominator against its
# regenerated finite null, and exact-length change windows (EC_EXACT).
#
# Mirrors run_all_n400.sh cell for cell at the PRINTED parameterisation
# (N_rep = 20 for F1/F2, 100 elsewhere; printed a-grids). Outputs carry a
# `_corrected` tag, which every aggregator filters out, so the corrected
# family never reaches the frozen thesis fragments; compare families with
# compare_exact_vs_legacy.R.
#
# Prerequisites (generated by the null-regeneration chain):
#   results-or-cache-src / SD_h_n2000_corrected.csv
#   results-or-cache-src / SD_h_F4_finite_corrected.csv
#   results-or-cache-src / E_n_beta_gamma_finite_corrected.csv
#
# Existing outputs are skipped, so the script resumes after an interrupt.
#
# Usage:  bash reproduction/sweeps/run_corrected_n400.sh

set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG="$ROOT/results/corrected_n400_$(date '+%Y%m%d_%H%M%S').log"
NCORES=20
mkdir -p "$ROOT/results"

log () { echo "[$(date '+%H:%M:%S')] $*" | tee -a "$LOG"; }

needs_run () {
  local f="$1"
  if [ -f "$f" ] && [ "$(wc -l < "$f")" -gt 1 ]; then
    log "SKIP $(basename "$f") (exists)"
    return 1
  fi
  return 0
}

run_driver () {
  local out_csv="$1"; shift
  needs_run "$out_csv" || return 0
  local pre=""
  for kv in "$@"; do pre+="$kv; "; done
  log "RUN $(basename "$out_csv")"
  Rscript -e "
    ${pre}
    EC_EXACT <- TRUE
    NCORES <- ${NCORES}L
    OUT_CSV <- '$out_csv'
    source('$ROOT/driver.R')
  " 2>&1 | tee -a "$LOG"
}

log "Starting corrected-family sweep. NCORES=$NCORES"

A_F1='c(1.5, 2, 2.5, 3, 5, 10)'
A_F2='c(0.5, 1, 1.5, 2, 5)'
A_F3='c(0.5, 1, 1.5, 2, 2.5, 5)'

# ---------------------------------------------------------------------------
# 1. Functional F1/F2/F3 -- Wilcoxon (27 cells)
# ---------------------------------------------------------------------------
log "=== F1/F2/F3 Wilcoxon corrected (27 cells) ==="
for proj in ito l2 c_max_var; do
  for m in 1 2 4; do
    for scen in F1 F2 F3; do
      m_suffix=""; [ "$m" -gt 1 ] && m_suffix="_m${m}"
      case "$scen" in
        F1) a_grid="$A_F1"; nrep=20  ;;
        F2) a_grid="$A_F2"; nrep=20  ;;
        F3) a_grid="$A_F3"; nrep=100 ;;
      esac
      out="$ROOT/results/wilcoxon_${scen}_n400_h_0_beta0_corrected_${proj}${m_suffix}.csv"
      run_driver "$out" \
        "METHOD <- 'wilcoxon'" "SCENARIO <- '$scen'" \
        "PROJECTION <- '$proj'" "WILCOXON_KERNEL <- 'h_0'" \
        "WILCOXON_SCAN <- 'corrected'" \
        "M <- ${m}L" "N <- 400L" "N_REP <- ${nrep}L" \
        "A_GRID <- $a_grid"
    done
  done
done

# ---------------------------------------------------------------------------
# 2. Functional F1/F2/F3 -- Lp (9 cells)
# ---------------------------------------------------------------------------
log "=== F1/F2/F3 Lp corrected (9 cells) ==="
for proj in ito l2 c_max_var; do
  for scen in F1 F2 F3; do
    case "$scen" in
      F1) a_grid="$A_F1"; nrep=20  ;;
      F2) a_grid="$A_F2"; nrep=20  ;;
      F3) a_grid="$A_F3"; nrep=100 ;;
    esac
    out="$ROOT/results/lp_${scen}_n400_p2_corrected_${proj}.csv"
    run_driver "$out" \
      "METHOD <- 'lp'" "SCENARIO <- '$scen'" \
      "PROJECTION <- '$proj'" "P <- 2L" "LP_VARIANT <- 'corrected'" \
      "N <- 400L" "N_REP <- ${nrep}L" \
      "A_GRID <- $a_grid"
  done
done

# ---------------------------------------------------------------------------
# 3. Functional F1/F2/F3 -- RKHS, calibrated corrected runner (9 cells)
# ---------------------------------------------------------------------------
log "=== F1/F2/F3 RKHS corrected calibrated (9 cells) ==="
Rscript "$ROOT/run_pareto_curves_rkhs_corrected_n400.R" 2>&1 | tee -a "$LOG"

# ---------------------------------------------------------------------------
# 4. F4 -- all four methods (16 cells)
# ---------------------------------------------------------------------------
log "=== F4 Wilcoxon corrected (9 cells) ==="
for proj in ito l2 c_max_var; do
  for m in 1 2 4; do
    m_suffix=""; [ "$m" -gt 1 ] && m_suffix="_m${m}"
    out="$ROOT/results/wilcoxon_F4_n400_h_0_beta0_corrected_${proj}${m_suffix}.csv"
    run_driver "$out" \
      "METHOD <- 'wilcoxon'" "SCENARIO <- 'F4'" \
      "PROJECTION <- '$proj'" "WILCOXON_KERNEL <- 'h_0'" \
      "WILCOXON_SCAN <- 'corrected'" \
      "M <- ${m}L" "N <- 400L"
  done
done

log "=== F4 Lp corrected (3 cells) ==="
for proj in ito l2 c_max_var; do
  out="$ROOT/results/lp_F4_n400_p2_corrected_${proj}.csv"
  run_driver "$out" \
    "METHOD <- 'lp'" "SCENARIO <- 'F4'" \
    "PROJECTION <- '$proj'" "P <- 2L" "LP_VARIANT <- 'corrected'" \
    "N <- 400L"
done

log "=== F4 RKHS corrected (3 cells) ==="
for proj in ito l2 c_max_var; do
  case "$proj" in
    l2) kern="min" ;;
    *)  kern="gaussian" ;;
  esac
  out="$ROOT/results/rkhs_F4_n400_${kern}_rnorm_corrected_${proj}.csv"
  run_driver "$out" \
    "METHOD <- 'rkhs'" "SCENARIO <- 'F4'" \
    "PROJECTION <- '$proj'" "KERNEL <- '$kern'" \
    "RKHS_VARIANT <- 'corrected'" \
    "N <- 400L"
done

log "=== F4 Birbilas corrected (1 cell) ==="
run_driver "$ROOT/results/birbilas_F4_n400_beta1_cv_adjusted_corrected.csv" \
  "METHOD <- 'birbilas'" "SCENARIO <- 'F4'" \
  "PROJECTION <- 'none'" "BIRBILAS_BETA_ID <- 'beta1'" \
  "BIRBILAS_CV <- 'adjusted'" "BIRBILAS_VARIANT <- 'corrected'" \
  "N <- 400L"

# ---------------------------------------------------------------------------
# 5. Scalar S1-S5 (23 cells)
# ---------------------------------------------------------------------------
log "=== Scalar S1-S5 Wilcoxon corrected (15 cells) ==="
for scen in S1 S2 S3 S4 S5; do
  for m in 1 2 4; do
    m_suffix=""; [ "$m" -gt 1 ] && m_suffix="_m${m}"
    out="$ROOT/results/wilcoxon_${scen}_n400_h_w_beta0_corrected${m_suffix}.csv"
    run_driver "$out" \
      "METHOD <- 'wilcoxon'" "SCENARIO <- '$scen'" \
      "PROJECTION <- 'none'" "WILCOXON_KERNEL <- 'h_w'" \
      "WILCOXON_SCAN <- 'corrected'" \
      "M <- ${m}L" "N <- 400L"
  done
done

log "=== Scalar S1-S5 Lp corrected (5 cells) ==="
for scen in S1 S2 S3 S4 S5; do
  out="$ROOT/results/lp_${scen}_n400_p2_corrected.csv"
  run_driver "$out" \
    "METHOD <- 'lp'" "SCENARIO <- '$scen'" \
    "PROJECTION <- 'none'" "P <- 2L" "LP_VARIANT <- 'corrected'" \
    "N <- 400L"
done

log "=== Scalar S1/S2/S4 RKHS corrected (3 cells) ==="
run_driver "$ROOT/results/rkhs_S1_n400_gaussian_rnorm_corrected.csv" \
  "METHOD <- 'rkhs'" "SCENARIO <- 'S1'" "PROJECTION <- 'none'" \
  "KERNEL <- 'gaussian'" "BASELINE <- ''" "RKHS_VARIANT <- 'corrected'" \
  "N <- 400L"
run_driver "$ROOT/results/rkhs_S2_n400_min_rnorm.sq_corrected.csv" \
  "METHOD <- 'rkhs'" "SCENARIO <- 'S2'" "PROJECTION <- 'none'" \
  "KERNEL <- 'min'" "BASELINE <- 'rnorm.sq'" "RKHS_VARIANT <- 'corrected'" \
  "N <- 400L"
run_driver "$ROOT/results/rkhs_S4_n400_2_max_rbeta.1.9_corrected.csv" \
  "METHOD <- 'rkhs'" "SCENARIO <- 'S4'" "PROJECTION <- 'none'" \
  "KERNEL <- '2_max'" "BASELINE <- 'rbeta.1.9'" "RKHS_VARIANT <- 'corrected'" \
  "N <- 400L"

# ---------------------------------------------------------------------------
# 6. Stability table, corrected scan
# ---------------------------------------------------------------------------
if needs_run "$ROOT/results/stability_summary_corrected.csv"; then
  log "=== Stability study, corrected scan ==="
  Rscript -e "
    WILCOXON_SCAN <- 'corrected'; EC_EXACT <- TRUE; NCORES <- ${NCORES}L
    OUT_RAW <- 'results/stability_raw_corrected.csv'
    OUT_SUMMARY <- 'results/stability_summary_corrected.csv'
    source('$ROOT/stability.R')
  " 2>&1 | tee -a "$LOG"
fi

log "Done. Log: $LOG"
