#!/usr/bin/env Rscript
# Driver: run one (method, scenario) combination across the cross-product
# (gamma, ec_interval, a) and write a tidy CSV with one row per cell. Edit
# the block below to change inputs.
#
# Ported from the thesis pipeline onto the fdachange package: the corrected
# variants dispatch to the package (bit-identical to the audited originals,
# see the package's golden-value tests), the legacy/exact variants to the
# vendored pre-audit implementations in R/legacy/, and the scenario
# generators / projections / split aggregation come from the package via
# R/compat.R. Flag semantics, RNG discipline and output format are unchanged
# from the original driver.
#
# Method contract (per method):
#   <method> statistic(X, gamma, ...)             -> scalar
#   <method>_null_distribution(n, gamma, ...)     -> numeric vector (legacy env)
# Method-specific ... args are resolved from `stat_args` / `null_args` below.
#
# Scenario contract (R/compat.R):
#   generate_<name>(n, a, ec.interval)            -> numeric vector or matrix

# ---- Inputs (edit these, or pre-set in .GlobalEnv from a wrapper) ---------
# `.def(name, value)` sets the default unless the caller has already assigned
# `name` in .GlobalEnv. Lets a wrapper script (e.g. `sweeps/run_F4_sweep.sh`)
# batch many runs by pre-setting METHOD / PROJECTION / etc. before sourcing
# this file. A bare `Rscript driver.R` just gets the defaults.
.def <- function(name, value) {
  if (!exists(name, envir = .GlobalEnv, inherits = FALSE)) {
    assign(name, value, envir = .GlobalEnv)
  }
}

.def("METHOD",     "far1")              # rkhs | lp | wilcoxon | far1
.def("SCENARIO",   "F4")                    # S1..S5 | F1..F4
.def("N",          200L)

# Cross-method comparison grid (matches the cached gammas in Lp / RKHS /
# Wilcoxon). Birbilas's canonical gamma = 0.4 is also cached and can be
# added if you want a Birbilas-only sweep.
.def("GAMMA_GRID", c(0, 0.25, 0.45))

.def("N_REP",      100L)                    # replications per alternative a
.def("ALPHA",      0.05)

# Ch.4 / Ch.5 grid: a in {0, 1/4, 1/2, 1, 2, 4, 8}; a = 0 is the size check.
.def("A_GRID",     c(0, 0.25, 0.5, 1, 2, 4, 8))

# Ch.4 / Ch.5 centered-window epidemic geometry:
#   l in {floor(log n) + 1, n/5}, k_star = floor(n/2) - floor(l/2).
# For n=200 this gives l in {6, 40}, k_star in {97, 80}, ec in
# {(0.485, 0.515), (0.400, 0.600)}.
.def("EC_GEOMETRY", function(n) {
  l_ints <- c(floor(log(n)) + 1L, n %/% 5L)
  lapply(l_ints, function(l) {
    k_star <- (n %/% 2L) - (l %/% 2L)
    c(k_star / n, (k_star + l) / n)
  })
})

# splits: n divided into m chunks of n/m. Paper 1's T^(d) outer-max
# aggregation. Must divide N; projection redrawn per chunk.
.def("M", 1L)

# Replicate-loop parallelism via mclapply.
.def("NCORES", 10L)

.def("SEED",       42L)
.def("OUT_CSV",    NULL)                    # NULL -> results/<method>_<scenario>_<tag>.csv

# RKHS-only:
.def("KERNEL",     "gaussian")              # gaussian | min | 2_max
.def("BASELINE",   "")                      # "" | "runif" | "rnorm.sq" (cache-dependent)

# Lp-only:
.def("P",          2L)                      # 2 | 4 | 10

# Wilcoxon-only:
.def("BETA",       0)                       # 0 everywhere; 1 only at gamma = 0.5
.def("WILCOXON_KERNEL", "h_w")              # h_w (paper 2, median) | h_0 (paper 1, norm)
# "legacy" is the scan that produced every printed table; it carries a
# summed-area off-by-one that drops column 1 from the complement and so
# understates the statistic by roughly 1 per cent at n = 400. "exact" fixes
# only that off-by-one. "corrected" is the statistic as the dissertation
# prints it (weight direction + index, all windows, closed-form gamma = 0
# null) -- see R/legacy/method_wilcoxon.R and verify_statistics.R. Runs tag
# their output `_exact` / `_corrected` so the families never share a CSV.
.def("WILCOXON_SCAN", "legacy")             # legacy | exact | corrected
# Per-method corrected-statistic switches (see the audit notes in each
# R/legacy/method_*.R; verify_statistics.R is the gate). "corrected" selects
# the printed formula and, where the null cache was generated by the legacy
# statistic (RKHS, Birbilas finite), the regenerated cache.
.def("LP_VARIANT",       "legacy")          # legacy | corrected
.def("RKHS_VARIANT",     "legacy")          # legacy | corrected
.def("FAR1_VARIANT", "legacy")          # legacy | corrected
# TRUE makes the scenario change window exactly l points, as the thesis
# defines I* = {k*+1..k*+l}; the legacy window carries l + 1 points.
.def("EC_EXACT", FALSE)

# Birbilas-only:
# beta1..beta4 (fdachange::far1_betas). Selects the FAR(1) coefficient
# operator used both in (I - beta) and in F4's data generator. beta1(t) =
# 0.7 sqrt(t) is canonical for power sims.
.def("FAR1_BETA_ID", "beta1")
# "adjusted" -- finite-sample empirical (1 - alpha) quantile of
# n^{-1/2+gamma} E_{n,beta,gamma} under H_0. Loads
# E_n_beta_gamma_finite[_corrected].csv. Matches dissertation Algorithm
# alg:zero / eq:adjusted_fit3 for n in [100, 1000].
# "asymptotic" -- cached E_{q,gamma}. Conservative for n < 1000.
.def("FAR1_CV", "adjusted")

# Functional-only (ignored when the scenario emits a numeric vector):
.def("PROJECTION", "none")                  # none | c_max_var | ito | l2 | wiener | pc1 | pc_d
.def("PC_D_N",     3L)                      # PC_d outer-max multiplicity (ignored unless PROJECTION == pc_d)

rm(.def, envir = .GlobalEnv)
# ---------------------------------------------------------------------------

script_path <- (function() {
  args <- commandArgs(trailingOnly = FALSE)
  key <- "--file="
  hit <- sub(key, "", args[grepl(key, args)])
  if (length(hit)) return(normalizePath(hit[1]))
  ofile <- sys.frame(1)$ofile
  if (!is.null(ofile)) return(normalizePath(ofile))
  NULL
})()
root <- if (is.null(script_path)) getwd() else dirname(script_path)

suppressPackageStartupMessages(library(fdachange))
source(file.path(root, "R", "compat.R"))
source(file.path(root, "R", "legacy_env.R"))
legacy <- legacy_env(root)

# Birbilas's E_{n,beta,gamma} consumes the full (l + 1) x n matrix; smoke /
# driver bypass the per-row scalar path via make_run(matrix_in = TRUE).
MATRIX_IN <- METHOD == "far1"
if (MATRIX_IN && PROJECTION != "none") {
  stop("far1 statistic ignores PROJECTION; set PROJECTION = 'none'.")
}
if (METHOD == "far1") {
  FAR1_BETA_T <- far1_beta_registry[[FAR1_BETA_ID]]
  if (is.null(FAR1_BETA_T)) {
    stop(sprintf("Unknown FAR1_BETA_ID '%s'; available: %s",
                 FAR1_BETA_ID,
                 paste(names(far1_beta_registry), collapse = ", ")))
  }
}

if (METHOD == "wilcoxon" && !WILCOXON_SCAN %in% c("legacy", "exact", "corrected")) {
  stop("WILCOXON_SCAN must be 'legacy', 'exact' or 'corrected', got '",
       WILCOXON_SCAN, "'")
}
for (.v in c("LP_VARIANT", "RKHS_VARIANT", "FAR1_VARIANT")) {
  if (!get(.v) %in% c("legacy", "corrected")) {
    stop(.v, " must be 'legacy' or 'corrected', got '", get(.v), "'")
  }
}
# Corrected variants dispatch to the package; legacy/exact to the vendored
# pre-audit implementations.
statistic <- switch(METHOD,
  wilcoxon = switch(WILCOXON_SCAN,
    legacy    = legacy$wilcoxon_statistic,
    exact     = legacy$wilcoxon_statistic_exact,
    corrected = fdachange::wilcoxon_statistic),
  lp       = if (LP_VARIANT       == "corrected") fdachange::lp_statistic
             else legacy$lp_statistic,
  rkhs     = if (RKHS_VARIANT     == "corrected") fdachange::rkhs_statistic
             else legacy$rkhs_statistic,
  far1 = if (FAR1_VARIANT == "corrected") fdachange::far1_statistic
             else legacy$far1_statistic)
null_dist_fn <- get(paste0(METHOD, "_null_distribution"), envir = legacy)
generate     <- get(paste0("generate_", SCENARIO))
project      <- if (PROJECTION == "pc_d") {
  function(X) project_pc_d(X, d = PC_D_N)
} else {
  projection_fn(PROJECTION)
}
proj_mult    <- projection_multiplicity(PROJECTION, PC_D_N)

# Per-method parameters are split into: `stat_args` (fed to the statistic
# alongside X, GAMMA) and `null_args` (fed to <method>_null_distribution
# alongside n, GAMMA).
stat_args <- switch(METHOD,
  rkhs     = list(kernel = kernel_fn(KERNEL)),
  lp       = list(p = P, cdf = get(paste0("cdf_", SCENARIO))),
  wilcoxon = list(beta = BETA, kernel = WILCOXON_KERNEL),
  far1 = list(beta_t = FAR1_BETA_T))

null_args <- switch(METHOD,
  rkhs     = if (SCENARIO == "F4") {
    # F4 dispatch goes through `load_rkhs_F4_null` keyed on
    # (n, gamma, projection, kernel_name).
    list(kernel_name = KERNEL, scenario_id = "F4", projection = PROJECTION,
         variant = RKHS_VARIANT)
  } else {
    list(kernel_name = KERNEL, baseline = BASELINE, variant = RKHS_VARIANT)
  },
  lp       = list(p = P),
  # The corrected Wilcoxon family swaps the provably-wrong gamma = 0 cache
  # cell for the closed-form Kuiper law; gamma > 0 columns stay cached.
  wilcoxon = list(beta = BETA,
                  exact_gamma0 = (WILCOXON_SCAN == "corrected")),
  far1 = list())

out_tag <- switch(METHOD,
  rkhs     = paste(KERNEL, if (nzchar(BASELINE)) BASELINE else "rnorm", sep = "_"),
  lp       = sprintf("p%d", P),
  wilcoxon = sprintf("%s_beta%s%s", WILCOXON_KERNEL, BETA,
                     switch(WILCOXON_SCAN, exact = "_exact",
                            corrected = "_corrected", "")),
  far1 = sprintf("%s_cv_%s", FAR1_BETA_ID, FAR1_CV))
# Corrected-variant runs must never share a CSV (or an aggregator glob match)
# with the legacy family.
if ((METHOD == "lp"       && LP_VARIANT       == "corrected") ||
    (METHOD == "rkhs"     && RKHS_VARIANT     == "corrected") ||
    (METHOD == "far1" && FAR1_VARIANT == "corrected")) {
  out_tag <- paste0(out_tag, "_corrected")
}
# Append the projection so a sweep over (method, projection) writes to
# distinct CSVs. Skipped for projection = "none" so scalar-scenario tags
# stay backward-compatible (e.g. `lp_S1_p2.csv`).
if (PROJECTION != "none") out_tag <- sprintf("%s_%s", out_tag, PROJECTION)
# Append the m-split when > 1 so a sweep over M (e.g. paper 1's T^(d)
# Wilcoxon at d in {1, 2, 4}) writes to distinct CSVs.
if (M > 1L) out_tag <- sprintf("%s_m%d", out_tag, M)

if (N %% M != 0L) {
  stop(sprintf("N = %d not divisible by M = %d", N, M))
}
# L'Ecuyer-CMRG: stable parallel RNG streams for mclapply (mc.set.seed).
RNGkind("L'Ecuyer-CMRG")
set.seed(SEED)
m_eff        <- M * proj_mult
ec_intervals <- EC_GEOMETRY(N)
total_reps   <- length(GAMMA_GRID) * length(ec_intervals) * length(A_GRID) * N_REP
cat(sprintf("[%s/%s proj=%s tag=%s] n=%d m=%d mult=%d N_rep=%d gammas=%d ecs=%d a-vals=%d total_reps=%d ncores=%d\n",
            METHOD, SCENARIO, PROJECTION, out_tag, N, M, proj_mult, N_REP,
            length(GAMMA_GRID), length(ec_intervals), length(A_GRID),
            total_reps, NCORES))
for (i in seq_along(ec_intervals)) {
  ec <- ec_intervals[[i]]
  cat(sprintf("  ec[%d] = (%.4f, %.4f)  l/n = %.4f\n", i, ec[1], ec[2], ec[2] - ec[1]))
}

# Pre-load null + critical value + run-on-chunk closure per gamma. mclapply
# children inherit these via fork.
gamma_setup <- lapply(GAMMA_GRID, function(g) {
  if (METHOD == "far1" && FAR1_CV == "adjusted") {
    null <- legacy$load_far1_finite_null(N, g, FAR1_BETA_ID,
                                             variant = FAR1_VARIANT)
    src  <- sprintf("finite[n=%d,beta=%s,%s]", N, FAR1_BETA_ID,
                    FAR1_VARIANT)
  } else {
    null <- do.call(null_dist_fn, c(list(N %/% M, g), null_args))
    src  <- "asymptotic"
  }
  cv <- critical_value(null, ALPHA, splits = m_eff)
  run <- make_run(project, statistic, g, stat_args, matrix_in = MATRIX_IN)
  cat(sprintf("[gamma=%.3f] %s null (%d draws); cv (%.0f%% ^ 1/%d) = %.4f\n",
              g, src, length(null), 100 * (1 - ALPHA), m_eff, cv))
  list(null = null, cv = cv, run = run)
})
names(gamma_setup) <- as.character(GAMMA_GRID)

# Flatten (gamma, ec_idx, a) into one task list so a single mclapply call
# load-balances cells across cores (each worker runs all N_REP of one cell
# serially -- no repeat fork overhead within a cell).
tasks <- expand.grid(gamma = GAMMA_GRID, ec_idx = seq_along(ec_intervals),
                     a = A_GRID,
                     KEEP.OUT.ATTRS = FALSE, stringsAsFactors = FALSE)

t0_total <- Sys.time()
run_task <- function(k) {
  g  <- tasks$gamma[k]
  ec <- ec_intervals[[tasks$ec_idx[k]]]
  a  <- tasks$a[k]
  gs <- gamma_setup[[as.character(g)]]
  t_cell <- Sys.time()
  stats <- numeric(N_REP)
  for (r in seq_len(N_REP)) {
    X <- generate(N, a, ec)
    stats[r] <- scan_over_splits(X, M, gs$run)
  }
  list(gamma = g, ec_start = ec[1], ec_end = ec[2], a = a,
       power = mean(stats > gs$cv), cv = gs$cv,
       cell_s = as.numeric(difftime(Sys.time(), t_cell, units = "secs")))
}

results <- parallel::mclapply(seq_len(nrow(tasks)), run_task,
                              mc.cores = NCORES, mc.set.seed = TRUE,
                              mc.preschedule = FALSE)
if (any(vapply(results, inherits, logical(1), "try-error"))) {
  stop("mclapply rep errored; rerun with NCORES=1 for a traceback")
}

rows <- lapply(results, function(res) {
  cat(sprintf("  gamma=%.2f ec=(%.3f,%.3f) a=%6.3f  power=%.3f  cell=%s\n",
              res$gamma, res$ec_start, res$ec_end, res$a, res$power,
              fmt_duration(res$cell_s)))
  data.frame(
    method = METHOD, scenario = SCENARIO, tag = out_tag,
    n = N, m = M, projection = PROJECTION,
    gamma = res$gamma, alpha = ALPHA, N_rep = N_REP,
    ec_start = res$ec_start, ec_end = res$ec_end,
    ec_length = res$ec_end - res$ec_start,
    a = res$a, power = res$power, critical_value = res$cv
  )
})
total_s <- as.numeric(difftime(Sys.time(), t0_total, units = "secs"))
cat(sprintf("total wall time: %s\n", fmt_duration(total_s)))
df <- do.call(rbind, rows)

if (is.null(OUT_CSV)) {
  OUT_CSV <- file.path(root, "results",
    sprintf("%s_%s_%s.csv", METHOD, SCENARIO, out_tag))
}
dir.create(dirname(OUT_CSV), showWarnings = FALSE, recursive = TRUE)
write.csv(df, OUT_CSV, row.names = FALSE)
cat("wrote ", OUT_CSV, "\n", sep = "")
