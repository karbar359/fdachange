#' RKHS scan test (Chapter 5 of the dissertation).
#'
#' Consumes a numeric sample X and returns the weighted RKHS scan statistic
#'   T_rho = max_{k,l : k+l <= n} sqrt(S(k,l)) * w(l/n) / sqrt(n)
#' where
#'   S(k,l) = sum_{i,j in [k,k+l]} K_ij
#'          - 2 * (l/n) * sum_{i in [k,k+l], j in [1,n]} K_ij
#'          + (l/n)^2 * sum_{i,j in [1,n]} K_ij.
#'
#' Callers load shared helpers once (integral_image.R, weights.R, kernels.R).

rkhs_statistic <- function(X, gamma, kernel, beta = 0) {
  n <- length(X)
  K <- gram(X, kernel)
  K.sum <- sum(K)
  sat   <- NumMatrix(K)$sat
  w     <- weight_cache(n, gamma, beta)

  # Vectorised scan over (k, m) with 1 <= k <= m <= n-1, l = m - k + 1.
  # Matches the previous nested loop bit-exactly; ~3x faster at n = 300.
  max_r <- nrow(sat); max_c <- ncol(sat)
  n1 <- n - 1L
  if (n1 < 1L) return(0)
  m_vec <- rep(seq_len(n1), times = seq_len(n1))
  k_vec <- sequence(seq_len(n1))
  l_vec <- m_vec - k_vec + 1L
  r2    <- pmin(m_vec + 2L, max_r)
  c2    <- pmin(m_vec + 2L, max_c)
  k1    <- k_vec + 1L
  c_end <- rep(max_c, length(k_vec))
  two   <- rep(2L,    length(k_vec))
  cross <- sat[cbind(r2, c_end)] - sat[cbind(r2, two)] -
           sat[cbind(k1, c_end)] + sat[cbind(k1, two)]
  B_km  <- sat[cbind(r2, c2)]    - sat[cbind(r2, k1)]  -
           sat[cbind(k1, c2)]    + sat[cbind(k1, k1)]
  l_n   <- l_vec / n
  s_km  <- B_km + l_n^2 * K.sum - 2 * l_n * cross
  s_km[s_km < 0] <- 0
  vals  <- sqrt(s_km) * w[l_vec]
  max(vals) / sqrt(n)
}

#' CORRECTED statistic: the printed formula, exactly (2026-09 audit, R1-R3).
#'
#' `rkhs_statistic` deviates from `ch5_rkhs/sec_theory.tex:60-62` three ways:
#'
#'   1. The cross term drops kernel column 1 (`sat[cbind(r2, two)]` subtracts
#'      j = 1) while the block and grand sums stay full, so every Delta^2 is
#'      inflated by the spurious positive term 2(l/n) sum_{i in I} K(X_i, X_1)
#'      -- first order in l^2/n, it does not vanish with n. For the 2-max
#'      kernel on Beta(1,9) data the spurious term dominates and the statistic
#'      degenerates to the near-constant sqrt(2 mean(K)); the printed
#'      tab:q-rkhs 2-max row (1.949 at every gamma) tabulates that constant.
#'   2. Windows never start at index 1 (thesis allows k = 0).
#'   3. No l <= n/2 restriction (thesis maxes over 1 <= l <= n/2).
#'
#'  The null caches were generated by `rkhs_statistic` itself, so the legacy
#'  family is self-consistently calibrated (level holds); it is just not the
#'  printed test. The corrected family follows the print and requires the
#'  regenerated null cache (`load_rkhs_null(..., variant = "corrected")`).
rkhs_statistic_corrected <- function(X, gamma, kernel, beta = 0) {
  co <- .rkhs_core_corrected(X, gamma, kernel, beta)
  if (is.null(co)) return(0)
  max(co$vals) / sqrt(co$n)
}

#' Corrected scan with argmax: returns the maximising window as (k, m) with
#' I = {k+1..m} plus the fractional interval, for the application tables.
rkhs_scan <- function(X, gamma, kernel, beta = 0) {
  co <- .rkhs_core_corrected(X, gamma, kernel, beta)
  if (is.null(co)) {
    return(list(stat = 0, k = NA_integer_, m = NA_integer_,
                interval = c(NA_real_, NA_real_)))
  }
  i_max <- which.max(co$vals)
  list(stat     = co$vals[i_max] / sqrt(co$n),
       k        = co$a_vec[i_max] - 1L,
       m        = co$b_vec[i_max],
       interval = c(co$a_vec[i_max] - 1L, co$b_vec[i_max]) / co$n)
}

.rkhs_core_corrected <- function(X, gamma, kernel, beta = 0) {
  n <- length(X)
  if (n < 2L) return(NULL)
  K <- gram(X, kernel)
  P <- matrix(0, n + 1L, n + 1L)
  P[-1L, -1L] <- t(apply(apply(K, 2L, cumsum), 1L, cumsum))
  K.sum <- P[n + 1L, n + 1L]
  w <- weight_cache(n, gamma, beta)

  # Windows I = {a..b}, length l = b - a + 1 <= n/2, all starts a >= 1.
  l_max <- n %/% 2L
  starts_per_l <- n - seq_len(l_max) + 1L         # l has n - l + 1 start points
  a_vec <- sequence(starts_per_l)
  l_rep <- rep.int(seq_len(l_max), starts_per_l)
  b_vec <- a_vec + l_rep - 1L
  rows  <- P[cbind(b_vec + 1L, n + 1L)] - P[cbind(a_vec, n + 1L)]
  block <- P[cbind(b_vec + 1L, b_vec + 1L)] - P[cbind(b_vec + 1L, a_vec)] -
           P[cbind(a_vec, b_vec + 1L)] + P[cbind(a_vec, a_vec)]
  l_n   <- l_rep / n
  s_km  <- block + l_n^2 * K.sum - 2 * l_n * rows
  s_km[s_km < 0] <- 0                     # clamp floating-point negatives
  list(vals = sqrt(s_km) * w[l_rep], a_vec = a_vec, b_vec = b_vec, n = n)
}

#' Null distribution dispatch.
#'
#' Default path: precomputed Monte-Carlo draws from
#' `.raw/SD_h_n2000_dist_t.csv`. Recomputing quantiles per gamma takes
#' weeks, so the cache is the source of truth. `kernel_name` must match a
#' CSV column stem (gaussian | min | 2_max) and `baseline` a CSV suffix
#' ("" | "runif" | "rnorm.sq") -- only some combinations were precomputed.
#'
#' Scenario-specific finite-null path: when `scenario_id == "F4"` (and a
#' `projection` is supplied), dispatch to `load_rkhs_F4_null`, which keys
#' on (n, gamma, projection, kernel_name). Used by the F4 cross-method
#' comparison so RKHS sees a calibrated CV at the test n rather than
#' falling through to a baseline-keyed asymptotic cache that does not
#' match F4's projected marginal.
rkhs_null_distribution <- function(n, gamma, kernel_name, baseline = "",
                                   scenario_id = "", projection = "",
                                   variant = "legacy", ...) {
  if (nzchar(scenario_id) && scenario_id == "F4") {
    return(load_rkhs_F4_null(n, gamma, projection, kernel_name,
                             variant = variant))
  }
  kernel_tag <- gsub("_", ".", kernel_name, fixed = TRUE)  # 2_max -> 2.max
  load_rkhs_null(gamma, kernel_tag, baseline, variant = variant)
}
